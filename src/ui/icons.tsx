export type IconName = keyof typeof ICONS | (string & {});

/** Draws a named icon at the current text size and colour. */
export function Icon({ name, className, size }: { name: IconName; className?: string; size?: number | string }) {
  const Glyph = ICONS[name] ?? LuSquare;
  return <Glyph className={className} size={size} aria-hidden />;
}

export function hasIcon(name: string): boolean {
  return name in ICONS;
}

export function iconComponent(name: IconName): IconType {
  return ICONS[name] ?? LuSquare;
}
